def render_text(source: Path, template_home: bool) -> str:
    text = source.read_text(encoding="utf-8")
    if template_home:
        text = text.replace(str(HOME), "{{ .chezmoi.homeDir }}")
        text = text.replace("screenDumpDir: {{ .chezmoi.homeDir }}/", 'screenDumpDir: "{{ .chezmoi.homeDir }}/')
        text = text.replace("/.local/state/k9s/screen-dumps\n", '/.local/state/k9s/screen-dumps"\n')
    return clean_text(text)


def clean_text(text: str) -> str:
    lines = [line.rstrip(" \t") for line in text.splitlines()]
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + ("\n" if lines else "")


def persist_entry(entry: ConfigEntry, apply: bool) -> dict[str, str]:
    source = HOME / entry.source
    target = REPO_ROOT / entry.target
    status = "missing"
    if source.exists():
        status = "would_copy"
        if apply:
            target.parent.mkdir(parents=True, exist_ok=True)
            try:
                target.write_text(render_text(source, entry.template_home), encoding="utf-8")
                shutil.copystat(source, target)
            except UnicodeDecodeError:
                shutil.copy2(source, target)
            status = "copied"
    return {
        "source": str(source),
        "target": str(target.relative_to(REPO_ROOT)),
        "status": status,
        "reason": entry.reason,
        "templateHome": str(entry.template_home).lower(),
    }


def write_manifest(rows: list[dict[str, str]], apply: bool) -> None:
    manifest = {
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "mode": "apply" if apply else "dry-run",
        "baseline": "schiff/tools/dev-notebooks-config manages SSH, proxy/autossh, zsh bootstrap, SOPS age key creation, Bitwarden CLI, eget, WSL container tooling, Krew and Atuin installation.",
        "included": rows,
        "excluded": [{"source": str(HOME / path), "reason": reason} for path, reason in sorted(EXCLUDED.items())],
    }
    path = REPO_ROOT / "dot_codex" / "knowledge" / "local-os-config-inventory.json"
    if apply:
        path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    else:
        print(json.dumps(manifest, indent=2, sort_keys=True))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="copy files into the dotfiles repo")
    args = parser.parse_args()

    rows = [persist_entry(entry, args.apply) for entry in SAFE_CONFIGS]
    write_manifest(rows, args.apply)
    for row in rows:
        print(f"{row['status']}: {row['source']} -> {row['target']}")
    print("excluded high-risk or baseline-managed files:", len(EXCLUDED))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

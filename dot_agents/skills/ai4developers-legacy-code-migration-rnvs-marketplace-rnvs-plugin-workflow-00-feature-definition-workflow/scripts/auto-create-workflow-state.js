#!/usr/bin/env node
/**
 * Auto-create .workflow-state.md when feature-definition.json is written
 *
 * Skill-scoped PostToolUse hook for Phase 0
 * Reads tool input from stdin (JSON format)
 */

const fs = require('fs');
const path = require('path');

// Read JSON input from stdin
let inputData = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', chunk => inputData += chunk);
process.stdin.on('end', () => {
    try {
        const input = JSON.parse(inputData);
        processHook(input);
    } catch (e) {
        console.error(`[Phase 0 Hook] Failed to parse input: ${e.message}`);
        process.exit(0); // Non-blocking - don't fail the write
    }
});

function processHook(input) {
    // Get file path from tool_input
    const filePath = input.tool_input?.file_path || '';

    // Only trigger for feature-definition.json files
    if (!filePath.endsWith('feature-definition.json')) {
        process.exit(0);
    }

    const resultsDir = path.dirname(filePath);
    const workflowStatePath = path.join(resultsDir, '.workflow-state.md');

    // Skip if already exists
    if (fs.existsSync(workflowStatePath)) {
        console.log(`[Phase 0] .workflow-state.md already exists`);
        process.exit(0);
    }

    // Extract data from feature-definition.json
    let featureName = path.basename(resultsDir);
    let migrationMode = 'UNKNOWN';

    try {
        const def = JSON.parse(fs.readFileSync(filePath, 'utf8'));
        featureName = def.feature_name || def.feature?.name || featureName;
        migrationMode = def.migration_mode || def.migration?.mode || 'UNKNOWN';
    } catch (e) {
        // Use defaults if parsing fails
    }

    const now = new Date();
    const timestamp = now.toISOString().slice(0, 16).replace('T', ' ');
    const date = now.toISOString().slice(0, 10);

    const content = `# ${featureName} Workflow State

**Mode**: ${migrationMode}
**Current Phase**: 0
**Status**: Complete
**Last Updated**: ${timestamp}

---

## Phase Completion

| Phase | Status | Key Output | Completed |
|-------|--------|------------|-----------|
| 0 | ✅ | feature-definition.json | ${timestamp} |
| 1 | ⬜ | file-inventory.json | - |
| 2 | ⬜ | dependencies.puml | - |
| 3 | ⬜ | ruletable.json | - |
| 4 | ⬜ | business-documentation.json | - |
| 5 | ⬜ | control-flow-mapping.json | - |
| 6 | ⬜ | analysis.json (VNRM) | - |
| 7 | ⬜ | microservice-design.json | - |
| 7.1 | ⬜ | microservice-changes-design.json | - |
| 8 | ⬜ | event-architecture.puml | - |
| 8.1 | ⬜ | control-flow-changes-design.json | - |
| 9 | ⬜ | traceability_matrix.json | - |
| 10 | ⬜ | jira_stories.csv | - |
| 11 | ⬜ | test-scenarios.md | - |
| 12 | ⬜ | unit_tests/ | - |
| 13 | ⬜ | source_code/ | - |
| 13.1 | ⬜ | applied-edits-log.json | - |
| 14 | ⬜ | test_scripts/ | - |
| 15 | ⬜ | quality_report.md | - |

**Legend**: ⬜ Pending | 🔄 In Progress | ✅ Complete | ⏭️ Skipped

---

## Session Context

**Last Activity**: Created feature definition for ${featureName}
**Next Action**: Run /01-code-analysis-workflow ${featureName}

---

## Decisions Log

| Date | Phase | Decision | Rationale |
|------|-------|----------|-----------|
| ${date} | 0 | Feature scope defined | Auto-generated by Phase 0 hook |

---

## Blockers & Concerns

(none)
`;

    try {
        fs.writeFileSync(workflowStatePath, content, 'utf8');
        console.log(`[Phase 0] Created .workflow-state.md for ${featureName}`);
    } catch (e) {
        console.error(`[Phase 0] Failed to create workflow state: ${e.message}`);
    }

    process.exit(0);
}
